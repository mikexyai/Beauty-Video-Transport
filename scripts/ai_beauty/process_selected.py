from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Iterable

PROJECT_BOOTSTRAP_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_BOOTSTRAP_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_BOOTSTRAP_ROOT))

from scripts.ai_beauty.db import connect
from scripts.ai_beauty.download_candidate import process_candidate
from scripts.ai_beauty.repositories.candidates import DEFAULT_CANDIDATE_REPOSITORY, CandidateRepository
from scripts.ai_beauty.repositories.uploads import upload_repository
from scripts.ai_beauty.state import ARCHIVED_STATUS, BATCH_SELECTED_STATUS, SCREENED_OUT_STATUS
from scripts.ai_beauty.record_screening import record_screening
from scripts.ai_beauty.upload_ai_beauty import main as upload_main


def _score_value(row: dict[str, Any]) -> float:
    try:
        return float(row.get("priority_score") or 0)
    except (TypeError, ValueError):
        return 0.0


def select_batch_rows(rows: Iterable[dict[str, Any]], *, limit: int | None = None) -> list[dict[str, Any]]:
    selected = [dict(r) for r in rows if r.get("candidate_status") == BATCH_SELECTED_STATUS]
    selected.sort(key=lambda r: (_score_value(r), str(r.get("aweme_id") or "")), reverse=True)
    return selected if limit is None else selected[:limit]


def build_screening_template(aweme_id: str, contact_sheet_path: str) -> dict[str, Any]:
    return {
        "contact_sheet_path": contact_sheet_path,
        "is_beauty_content": None,
        "suitable_for_ai_beauty": None,
        "visible_minor_risk": None,
        "low_quality": None,
        "obvious_watermark": None,
        "duplicate_risk": "unknown",
        "sensuality_level": "unknown",
        "explicitness_level": "unknown",
        "content_type": [],
        "visual_style": [],
        "motion_type": [],
        "decision": "review",
        "skip_reason": "Needs vision screening before upload.",
        "recommended_title": f"AI Beauty Short {aweme_id}",
        "recommended_tags": ["AI Beauty"],
        "selection_reason": "Template generated by process_selected.py; replace with vision screening result before approval.",
    }


def fetch_batch_selected(limit: int = 3) -> list[dict[str, Any]]:
    with connect() as conn:
        cur = conn.execute(
            """
            SELECT aweme_id, candidate_status, priority_score, douyin_url, caption,
                   local_video_path, analysis_dir, last_error
            FROM beauty.ai_beauty_candidates
            WHERE candidate_status = %s
            ORDER BY priority_score DESC, discovered_at ASC
            LIMIT %s
            """,
            (BATCH_SELECTED_STATUS, limit),
        )
        cols = [d.name for d in cur.description]
        return [dict(zip(cols, row)) for row in cur.fetchall()]


def write_template_if_missing(aweme_id: str, contact_sheet: str) -> Path:
    analysis_dir = Path(contact_sheet).parent
    path = analysis_dir / "screening_template.json"
    if not path.exists():
        path.write_text(json.dumps(build_screening_template(aweme_id, contact_sheet), ensure_ascii=False, indent=2), encoding="utf-8")
    return path


def archive_candidate(
    aweme_id: str,
    reason: str,
    *,
    status: str = ARCHIVED_STATUS,
    repository: CandidateRepository = DEFAULT_CANDIDATE_REPOSITORY,
) -> None:
    repository.mark_status(aweme_id, status, reason)


def delete_local_video(aweme_id: str, *, update_upload_record: bool = True) -> dict[str, Any]:
    local_video_path = upload_repository.fetch_candidate_local_video_path(aweme_id)
    path = Path(local_video_path) if local_video_path else None
    deleted = False
    size_before = None
    if path and path.exists():
        size_before = path.stat().st_size
        path.unlink()
        deleted = not path.exists()
    if update_upload_record:
        upload_repository.mark_local_file_deleted(aweme_id, deleted)
    return {"path": str(path) if path else None, "size_before": size_before, "deleted": deleted}


def should_cleanup_after_decision(decision: str | None) -> bool:
    return str(decision or "").strip().lower() in {"skipped", "review", "failed"}


def run_upload_cli(aweme_id: str, *, dry_run: bool = False) -> int:
    old_argv = sys.argv[:]
    try:
        sys.argv = ["upload_ai_beauty.py", "--aweme-id", aweme_id, "--dry-run" if dry_run else "--upload"]
        return int(upload_main())
    finally:
        sys.argv = old_argv


def process_one(row: dict[str, Any], *, auto_upload: bool = False, template_only: bool = False) -> dict[str, Any]:
    aweme_id = str(row["aweme_id"])
    result: dict[str, Any] = {"aweme_id": aweme_id}
    if template_only:
        contact_sheet = row.get("analysis_dir") and str(Path(row["analysis_dir"]) / "contact_sheet.jpg")
        if not contact_sheet:
            contact_sheet = f"analysis/douyin_ai_beauty/{aweme_id}/contact_sheet.jpg"
        result["screening_template"] = str(write_template_if_missing(aweme_id, contact_sheet))
        return result

    download = process_candidate(aweme_id)
    result["download"] = download
    if download.get("status") != "downloaded":
        result["status"] = "download_failed"
        return result
    template_path = write_template_if_missing(aweme_id, str(download["contact_sheet"]))
    result["screening_template"] = str(template_path)
    result["status"] = "needs_screening"

    screening_path = Path(download["contact_sheet"]).parent / "screening.json"
    if not screening_path.exists():
        result["message"] = "Create screening.json from vision analysis, then rerun with --auto-upload."
        return result

    data = json.loads(screening_path.read_text(encoding="utf-8"))
    screening_id = record_screening(aweme_id, data, model_name=data.get("model_name") or "manual-or-vision")
    result["screening_id"] = screening_id
    result["decision"] = data.get("decision")
    if data.get("decision") != "approved":
        archive_candidate(aweme_id, f"Screened out after screening decision: {data.get('decision')}", status=SCREENED_OUT_STATUS)
        result["status"] = "screened_not_uploaded"
        result["candidate_status"] = SCREENED_OUT_STATUS
        if should_cleanup_after_decision(data.get("decision")):
            result["cleanup"] = delete_local_video(aweme_id, update_upload_record=False)
        return result
    if not auto_upload:
        result["status"] = "approved_not_uploaded"
        result["message"] = "Rerun with --auto-upload to upload approved screening."
        return result
    dry_rc = run_upload_cli(aweme_id, dry_run=True)
    upload_rc = run_upload_cli(aweme_id, dry_run=False) if dry_rc == 0 else dry_rc
    result["dry_run_rc"] = dry_rc
    result["upload_rc"] = upload_rc
    result["cleanup"] = delete_local_video(aweme_id) if upload_rc == 0 else None
    result["status"] = "uploaded" if upload_rc == 0 else "upload_failed"
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description="Process current AI Beauty batch_selected candidates: download, prepare screening templates, and optionally upload approved screenings.")
    parser.add_argument("--limit", type=int, default=3)
    parser.add_argument("--aweme-id")
    parser.add_argument("--auto-upload", action="store_true", help="Upload if screening.json exists and decision is approved")
    parser.add_argument("--template-only", action="store_true", help="Only create screening templates, no download/upload")
    args = parser.parse_args()

    rows = fetch_batch_selected(limit=args.limit)
    if args.aweme_id:
        rows = [r for r in rows if r["aweme_id"] == args.aweme_id] or [{"aweme_id": args.aweme_id, "candidate_status": BATCH_SELECTED_STATUS, "priority_score": 0}]
    rows = select_batch_rows(rows, limit=args.limit)
    results = [process_one(row, auto_upload=args.auto_upload, template_only=args.template_only) for row in rows]
    print(json.dumps({"count": len(results), "results": results}, ensure_ascii=False, indent=2, default=str))
    return 0 if all(r.get("status") not in {"download_failed", "upload_failed"} for r in results) else 1


if __name__ == "__main__":
    raise SystemExit(main())
