from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

PROJECT_BOOTSTRAP_ROOT = Path(__file__).resolve().parents[2]
if str(PROJECT_BOOTSTRAP_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_BOOTSTRAP_ROOT))

from scripts.ai_beauty.db import connect


def _score(row: dict[str, Any]) -> float:
    views = float(row.get("views") or 0)
    likes = float(row.get("likes") or 0)
    comments = float(row.get("comments") or 0)
    return views + likes * 20 + comments * 10


def build_strategy_recommendations(rows: list[dict[str, Any]], *, min_samples: int = 5) -> dict[str, Any]:
    tag_stats: dict[str, dict[str, Any]] = defaultdict(lambda: {"videos": 0, "views": 0, "likes": 0, "comments": 0, "score": 0.0})
    for row in rows:
        tags = row.get("tags") or []
        if isinstance(tags, str):
            tags = [tags]
        for tag in tags:
            key = str(tag).strip()
            if not key:
                continue
            stat = tag_stats[key]
            stat["videos"] += 1
            stat["views"] += int(row.get("views") or 0)
            stat["likes"] += int(row.get("likes") or 0)
            stat["comments"] += int(row.get("comments") or 0)
            stat["score"] += _score(row)
    top_tags = [
        {"tag": tag, **stat, "avg_score": round(stat["score"] / max(1, stat["videos"]), 2)}
        for tag, stat in tag_stats.items()
    ]
    top_tags.sort(key=lambda x: (x["avg_score"], x["views"], x["tag"]), reverse=True)
    sample_size = len(rows)
    confidence = "low" if sample_size < min_samples else "medium" if sample_size < 20 else "high"
    suggestions = []
    if top_tags:
        suggestions.append(f"Favor candidates visually matching top tag '{top_tags[0]['tag']}' while sample confidence is {confidence}.")
    if confidence == "low":
        suggestions.append("Collect more AI Beauty uploads before making aggressive ranking changes.")
    return {
        "strategy_version": "ai_beauty_metrics_v1",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "sample_size": sample_size,
        "confidence": confidence,
        "top_tags": top_tags[:10],
        "suggestions": suggestions,
        "evidence": {"uploads_analyzed": sample_size, "min_samples": min_samples, "ranking_basis": "views + likes*20 + comments*10 by tag"},
    }


def fetch_metric_rows(limit: int = 50) -> list[dict[str, Any]]:
    with connect() as conn:
        cur = conn.execute(
            """
            SELECT u.youtube_video_id, u.title, u.tags, m.views, m.likes, m.comments, m.metric_date
            FROM beauty.ai_beauty_uploads u
            JOIN LATERAL (
              SELECT * FROM beauty.ai_beauty_video_metrics m
              WHERE m.youtube_video_id = u.youtube_video_id
              ORDER BY m.metric_date DESC, m.created_at DESC
              LIMIT 1
            ) m ON true
            ORDER BY u.uploaded_at DESC, u.id DESC
            LIMIT %s
            """,
            (limit,),
        )
        cols = [d.name for d in cur.description]
        return [dict(zip(cols, row)) for row in cur.fetchall()]


def store_strategy(recommendations: dict[str, Any]) -> int:
    with connect() as conn:
        row = conn.execute(
            """
            INSERT INTO beauty.ai_beauty_strategy_state (strategy_version, strategy_json, evidence_json, notes)
            VALUES (%s, %s, %s, %s)
            RETURNING id
            """,
            (
                recommendations.get("strategy_version"),
                json.dumps(recommendations, ensure_ascii=False),
                json.dumps(recommendations.get("evidence") or {}, ensure_ascii=False),
                "Generated by scripts/ai_beauty/update_strategy.py",
            ),
        ).fetchone()
        conn.commit()
    return int(row[0])


def main() -> int:
    parser = argparse.ArgumentParser(description="Build AI Beauty strategy recommendations from stored metrics.")
    parser.add_argument("--limit", type=int, default=50)
    parser.add_argument("--min-samples", type=int, default=5)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    rows = fetch_metric_rows(limit=args.limit)
    recommendations = build_strategy_recommendations(rows, min_samples=args.min_samples)
    strategy_id = None if args.dry_run else store_strategy(recommendations)
    print(json.dumps({"strategy_id": strategy_id, "recommendations": recommendations}, ensure_ascii=False, indent=2, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
